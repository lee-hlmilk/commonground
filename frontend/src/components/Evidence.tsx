import { CheckCircle2, CircleAlert, ShieldCheck } from 'lucide-react';
import type { Check, Flight, Message, Scenario } from '../types';
import { airlineName, json } from '../lib/format';

export function Evidence({scenario: s, flight: f, summary}: {scenario: Scenario | null; flight: Flight | null; summary: Record<string, unknown> | null}) {
  if (f) return <div className="evidence-body">
    <span className="tag historical">HISTORICAL SOURCE</span>
    <h3>{airlineName(f.airline)} · {f.origin.code} → {f.destination.code}</h3>
    <p>Tail number {f.tail_number}. These recorded outcomes are separate from the simulated recovery plan.</p>
    <dl className="kv">{(['scheduled_departure', 'departure_time', 'wheels_off', 'wheels_on', 'scheduled_arrival', 'arrival_time', 'arrival_delay', 'weather_delay', 'late_aircraft_delay', 'distance'] as const).map(k => <div key={k}><dt>{k.replace(/_/g, ' ')}</dt><dd>{String(f.historical[k] ?? '—')}</dd></div>)}</dl>
    <h3>Trace to original record</h3>
    <pre>{json(f.source)}</pre>
    <h3>Scenario operational inputs</h3>
    <pre>{json({reference_arrival: f.reference_arrival, latest_arrival: f.latest_arrival, taxi_in: f.taxi_in, taxi_out: f.taxi_out, turnaround: f.turnaround, scheduled_departure: f.scheduled_departure})}</pre>
    <h3>Full historical record</h3>
    <pre>{json(f.historical)}</pre>
  </div>;
  return <div className="evidence-body">
    <div className="callout"><ShieldCheck size={20}/><p>Real flight identities and recorded outcomes anchor the scenario. Waiting limits, runway restrictions, stands and handling resources are explicitly simulated.</p></div>
    <h3>Simulation assumptions</h3>
    <div className="assumption-list">{s?.assumptions.map((a, i) => <div key={a.id ?? i}><span className={`tag ${a.source === 'historical-derived' ? 'historical' : 'simulated'}`}>{a.source}</span><strong>{a.label}</strong><p>{typeof a.value === 'object' ? json(a.value) : String(a.value)} {a.unit ?? ''}</p></div>)}</div>
    <h3>External approvals</h3>
    {s?.approvals.length ? s.approvals.map(a => <div className="approval-row" key={a.id}><span>{a.label}</span><b className={a.status}>{a.status}</b></div>) : <p>No external approval dependency in this scenario.</p>}
    <h3>Scenario provenance</h3>
    <pre>{json(s?.provenance ?? {})}</pre>
    <h3>Source coverage</h3>
    <p>The supplied records are a disruption-focused subset. They cannot establish normal airport capacity or complete aircraft rotations.</p>
    <pre>{json(summary ?? {})}</pre>
  </div>;
}

export function DecisionDetails({message}: {message: Message}) {
  const claudeFallback = message.fallback?.from === 'jev' && message.fallback?.to === 'claude';
  const jev = message.provider === 'jev' || message.statement_source === 'template_from_jev_decision';
  if (!jev && !claudeFallback) return null;
  const decision = claudeFallback ? message.primary_decision : message.decision;
  return <div className={`jev-decision ${claudeFallback ? 'claude' : ''}`}>
    <span className="decision-source">{claudeFallback ? 'Claude fallback · low-confidence Jev decision' : 'Jev decision · template-rendered wording'}</span>
    {decision && <details><summary>{claudeFallback ? 'Inspect Jev handoff & model usage' : 'Inspect typed decision & probabilities'}</summary>
      <p>{claudeFallback ? 'Jev returned an uncertain decision. Claude generated the response above from the same participant context.' : 'Jev selects from supplied options. The wording above is rendered by the application, not generated by Jev.'} Probabilities do not replace operational checks or human approval.</p>
      {claudeFallback && <pre>{json(message.fallback)}</pre>}
      <pre>{json(decision)}</pre>
      {message.primary_usage && <pre>{json({primary_usage: message.primary_usage})}</pre>}
      {message.usage && <pre>{json({response_usage: message.usage})}</pre>}
    </details>}
  </div>;
}

export function CheckRow({check}: {check: Check}) {
  return <div className={`check-row ${check.passed ? 'pass' : 'fail'}`}>
    {check.passed ? <CheckCircle2 size={15}/> : <CircleAlert size={15}/>}
    <div><strong>{check.label}</strong><p>{check.detail}</p></div>
    <b>{check.passed ? 'PASS' : 'UNRESOLVED'}</b>
  </div>;
}
